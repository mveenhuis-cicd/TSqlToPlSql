-- Konvertiert von T-SQL nach PL/SQL (Ziel: Oracle 19c)
-- Automatische Umsetzung – Ergebnis prüfen, Stellen mit TODO manuell nacharbeiten.
--
-- Hinweise:
--   * Bezeichner 'Level' ist in Oracle reserviert → als "LEVEL" gequotet.
--   * INCLUDE-Spalten im Index gibt es in Oracle nicht (ggf. als Schlüsselspalten anhängen).
--   * DATEADD(month/year) → ADD_MONTHS: am Monatsende abweichend (ADD_MONTHS springt auf den letzten Tag).
--   * RETURN <wert> in Prozeduren → in Oracle als OUT-Parameter abbilden.
--   * Ergebnismengen (SELECT ohne INTO) → OPEN cursor FOR ... + DBMS_SQL.RETURN_RESULT (ab Oracle 12c).
-- ============================================================================

-- Kundentabelle
CREATE TABLE Kunde (
    KundeId NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    Name NVARCHAR2(100) NOT NULL,
    Email VARCHAR2(255) NULL,
    "LEVEL" NUMBER(3) DEFAULT 0 NOT NULL,
    Aktiv NUMBER(1) DEFAULT (1) NOT NULL,
    Notiz NCLOB NULL,
    ErstelltAm TIMESTAMP(3) DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_Kunde PRIMARY KEY (KundeId)
);

CREATE INDEX IX_Kunde_Name ON Kunde (Name);

INSERT INTO Kunde (Name, Email)
SELECT N'Müller', 'm@x.de' FROM DUAL UNION ALL
SELECT N'Meier', NULL FROM DUAL;

SELECT KundeId, Name || ' <' || NVL(Email, '-') || '>' AS Anzeige, (TRUNC(SYSDATE) - TRUNC(ErstelltAm)) AS Tage
FROM Kunde k
WHERE LENGTH(Name) > 3 AND ErstelltAm >= ADD_MONTHS(SYSDATE, -6)
ORDER BY Name FETCH FIRST 10 ROWS ONLY;

CREATE OR REPLACE PROCEDURE usp_KundeAnlegen (
    p_Name IN NVARCHAR2,
    p_Email IN VARCHAR2 DEFAULT NULL,
    p_NeueId IN OUT NUMBER
)
AS
    v_Anzahl NUMBER(10) := 0;
    v_Msg VARCHAR2(200);
    v_exists1 NUMBER(1);
    v_err_msg VARCHAR2(4000);
BEGIN
    SELECT CASE WHEN EXISTS (
        SELECT 1 FROM Kunde WHERE Email = p_Email
    ) THEN 1 ELSE 0 END INTO v_exists1 FROM DUAL;
    IF v_exists1 = 1 THEN
        RAISE_APPLICATION_ERROR(-20000, 'Kunde mit E-Mail ' || p_Email || ' existiert bereits');
        RETURN; -- TODO: Rückgabewert -1 → OUT-Parameter
    END IF;
    BEGIN
        -- BEGIN TRANSACTION: in Oracle implizit (Transaktion beginnt mit der ersten DML)
        INSERT INTO Kunde (Name, Email) VALUES (p_Name, p_Email)
        RETURNING KundeId INTO p_NeueId;
        SELECT COUNT(*) INTO v_Anzahl FROM Kunde;
        v_Msg := 'Kunde ' || CAST(p_NeueId AS VARCHAR2(10)) || ' angelegt, gesamt: ' || CAST(v_Anzahl AS VARCHAR2(10));
        DBMS_OUTPUT.PUT_LINE(v_Msg);
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            v_err_msg := SQLERRM;
            -- IF @@TRANCOUNT > 0: in Oracle nicht nötig
            ROLLBACK;
            INSERT INTO FehlerLog (Meldung, Zeit) VALUES (v_err_msg, SYSDATE);
            RAISE;
    END;
END usp_KundeAnlegen;
