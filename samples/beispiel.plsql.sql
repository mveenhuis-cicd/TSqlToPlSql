CREATE OR REPLACE FUNCTION fn_Alter (
    p_Geburt IN DATE
)
RETURN NUMBER
AS
    v_a NUMBER(10);
BEGIN
    v_a := (EXTRACT(YEAR FROM SYSDATE) - EXTRACT(YEAR FROM p_Geburt));
    IF ADD_MONTHS(p_Geburt, 12 * v_a) > SYSDATE THEN
        v_a := v_a - 1;
    END IF;
    RETURN v_a;
END fn_Alter;
