CREATE OR REPLACE PROCEDURE usp_Report (
    p_Ab IN TIMESTAMP
)
AS
    v_Id NUMBER(10);
    v_Name NVARCHAR2(100);
    v_i NUMBER(10) := 0;
    CURSOR cur IS
        SELECT KundeId, Name FROM Kunde WHERE ErstelltAm >= p_Ab;
    c_result1 SYS_REFCURSOR;
BEGIN
    OPEN cur;
    FETCH cur INTO v_Id, v_Name;
    WHILE cur%FOUND LOOP
        v_i := v_i + 1;
        IF MOD(v_i, 100) = 0 THEN
            DBMS_OUTPUT.PUT_LINE('Zeile ' || CAST(v_i AS VARCHAR2(10)));
        ELSIF v_Name LIKE 'A%' THEN
            DBMS_OUTPUT.PUT_LINE(v_Name);
        ELSE
            DBMS_OUTPUT.PUT_LINE(TO_CHAR(p_Ab, 'DD.MM.YYYY'));
        END IF;
        FETCH cur INTO v_Id, v_Name;
    END LOOP;
    CLOSE cur;
    OPEN c_result1 FOR
        SELECT k.KundeId, k.Name FROM Kunde k INNER JOIN Bestellung b ON b.KundeId = k.KundeId
        WHERE b.Datum BETWEEN p_Ab AND SYSDATE;
    DBMS_SQL.RETURN_RESULT(c_result1);
END usp_Report;
