using TSqlToPlSql;
using Xunit;

namespace TSqlToPlSql.Tests;

public class ConverterTests
{
    static string Conv(string tsql, OracleVersion target = OracleVersion.Oracle19c) =>
        new TSqlToPlSqlConverter(new ConversionOptions { IncludeHeader = false, Target = target }).Convert(tsql).Output;

    static string Norm(string s) => System.Text.RegularExpressions.Regex.Replace(s, @"\s+", " ").Trim();

    static void Has(string output, string expected) =>
        Assert.Contains(Norm(expected), Norm(output));

    // ------------------------------------------------------------------ Funktionen / Ausdrücke

    [Fact]
    public void Functions_AreMapped()
    {
        var o = Conv("SELECT ISNULL(a, 0), LEN(b), GETDATE(), SUBSTRING(c, 1, 3), CHARINDEX('x', d) FROM t");
        Has(o, "SELECT NVL(a, 0), LENGTH(b), SYSDATE, SUBSTR(c, 1, 3), INSTR(d, 'x') FROM t;");
    }

    [Fact]
    public void StringConcatenation_UsesPipes()
    {
        var o = Conv("SELECT Vorname + ' ' + Nachname AS Name, Menge + 1 FROM Person");
        Has(o, "Vorname || ' ' || Nachname AS Name, Menge + 1");
    }

    [Fact]
    public void Top_BecomesFetchFirst()
    {
        var o = Conv("SELECT TOP 5 * FROM Kunde ORDER BY Name");
        Has(o, "SELECT * FROM Kunde ORDER BY Name FETCH FIRST 5 ROWS ONLY;");
    }

    [Fact]
    public void SelectWithoutFrom_GetsDual_On19c_ButNotOn23ai()
    {
        Has(Conv("SELECT 1 + 1"), "SELECT 1 + 1 FROM DUAL;");
        Assert.DoesNotContain("DUAL", Conv("SELECT 1 + 1", OracleVersion.Oracle23ai));
    }

    [Fact]
    public void DateFunctions_AreMapped()
    {
        var o = Conv("SELECT DATEADD(day, 7, d), DATEADD(month, 1, d), DATEDIFF(day, a, b), YEAR(d) FROM t");
        Has(o, "d + 7, ADD_MONTHS(d, 1), (TRUNC(b) - TRUNC(a)), EXTRACT(YEAR FROM d)");
    }

    [Fact]
    public void ConvertWithStyle_UsesToChar()
    {
        Has(Conv("SELECT CONVERT(VARCHAR(10), d, 104) FROM t"), "TO_CHAR(d, 'DD.MM.YYYY')");
    }

    [Fact]
    public void Brackets_Dbo_And_Hints_AreRemoved()
    {
        var o = Conv("SELECT [k].[Name] FROM [dbo].[Kunde] AS [k] WITH (NOLOCK)");
        Has(o, "SELECT k.Name FROM Kunde k;");
    }

    [Fact]
    public void AliasAssignmentSyntax_IsRewritten()
    {
        Has(Conv("SELECT Gesamt = SUM(Betrag) FROM Rechnung"), "SELECT SUM(Betrag) AS Gesamt FROM Rechnung;");
    }

    [Fact]
    public void ReservedIdentifier_IsQuoted()
    {
        Has(Conv("SELECT [Level], [Date] FROM t"), "SELECT \"LEVEL\", \"DATE\" FROM t;");
    }

    [Fact]
    public void Modulo_BecomesMod()
    {
        Has(Conv("SELECT a % 3 FROM t"), "SELECT MOD(a, 3) FROM t;");
    }

    // ------------------------------------------------------------------ DDL

    [Fact]
    public void CreateTable_MapsTypesIdentityAndDefaults()
    {
        var o = Conv(@"CREATE TABLE dbo.Kunde (
            Id INT IDENTITY(1,1) NOT NULL,
            Name NVARCHAR(100) NOT NULL DEFAULT N'',
            Notiz VARCHAR(MAX) NULL,
            Aktiv BIT NOT NULL CONSTRAINT DF_A DEFAULT 1,
            CONSTRAINT PK_Kunde PRIMARY KEY CLUSTERED (Id ASC)
        ) ON [PRIMARY]");
        Has(o, "Id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL");
        Has(o, "Name NVARCHAR2(100) DEFAULT N'' NOT NULL");
        Has(o, "Notiz CLOB NULL");
        Has(o, "Aktiv NUMBER(1) DEFAULT 1 NOT NULL");
        Has(o, "CONSTRAINT PK_Kunde PRIMARY KEY (Id)");
        Assert.DoesNotContain("PRIMARY]", o);
    }

    [Fact]
    public void DropIfExists_On19c_UsesExceptionBlock()
    {
        var o = Conv("DROP TABLE IF EXISTS dbo.Alt");
        Has(o, "EXECUTE IMMEDIATE 'DROP TABLE Alt'");
        Has(o, "IF SQLCODE != -942 THEN RAISE; END IF;");
    }

    [Fact]
    public void MultiRowInsert_On19c_UsesUnionAll()
    {
        var o = Conv("INSERT INTO t (a, b) VALUES (1, 'x'), (2, 'y')");
        Has(o, "INSERT INTO t (a, b) SELECT 1, 'x' FROM DUAL UNION ALL SELECT 2, 'y' FROM DUAL;");
    }

    // ------------------------------------------------------------------ PL/SQL

    [Fact]
    public void Procedure_WithParamsAndOutput()
    {
        var o = Conv(@"CREATE PROCEDURE dbo.p_Test @Id INT, @Name VARCHAR(50) = NULL, @Res INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET @Res = @Id * 2;
END");
        Has(o, "CREATE OR REPLACE PROCEDURE p_Test ( p_Id IN NUMBER, p_Name IN VARCHAR2 DEFAULT NULL, p_Res IN OUT NUMBER )");
        Has(o, "p_Res := p_Id * 2;");
        Has(o, "END p_Test;");
        Assert.DoesNotContain("NOCOUNT", o);
    }

    [Fact]
    public void IfElseIf_BecomesElsif()
    {
        var o = Conv(@"DECLARE @x INT = 1;
IF @x = 1 PRINT 'eins'
ELSE IF @x = 2 PRINT 'zwei'
ELSE PRINT 'andere'");
        Has(o, "IF v_x = 1 THEN DBMS_OUTPUT.PUT_LINE('eins'); ELSIF v_x = 2 THEN DBMS_OUTPUT.PUT_LINE('zwei'); ELSE DBMS_OUTPUT.PUT_LINE('andere'); END IF;");
    }

    [Fact]
    public void IfExists_IsHoisted()
    {
        var o = Conv(@"DECLARE @n INT;
IF EXISTS (SELECT 1 FROM t WHERE id = 1) SET @n = 1;");
        Has(o, "SELECT CASE WHEN EXISTS ( SELECT 1 FROM t WHERE id = 1 ) THEN 1 ELSE 0 END INTO v_exists1 FROM DUAL;");
        Has(o, "IF v_exists1 = 1 THEN");
    }

    [Fact]
    public void SelectAssignment_BecomesSelectInto()
    {
        var o = Conv(@"DECLARE @c INT, @m DATETIME;
SELECT @c = COUNT(*), @m = MAX(Datum) FROM Rechnung;");
        Has(o, "SELECT COUNT(*), MAX(Datum) INTO v_c, v_m FROM Rechnung;");
    }

    [Fact]
    public void TryCatch_BecomesException()
    {
        var o = Conv(@"BEGIN TRY
    DELETE FROM t;
END TRY
BEGIN CATCH
    INSERT INTO log (msg) VALUES (ERROR_MESSAGE());
    THROW;
END CATCH");
        Has(o, "BEGIN DELETE FROM t; EXCEPTION WHEN OTHERS THEN v_err_msg := SQLERRM; INSERT INTO log (msg) VALUES (v_err_msg); RAISE; END;");
    }

    [Fact]
    public void Cursor_Loop()
    {
        var o = Conv(@"DECLARE @id INT;
DECLARE c CURSOR FOR SELECT id FROM t;
OPEN c;
FETCH NEXT FROM c INTO @id;
WHILE @@FETCH_STATUS = 0
BEGIN
    PRINT @id;
    FETCH NEXT FROM c INTO @id;
END
CLOSE c;
DEALLOCATE c;");
        Has(o, "CURSOR c IS SELECT id FROM t;");
        Has(o, "WHILE c%FOUND LOOP");
        Has(o, "FETCH c INTO v_id;");
    }

    [Fact]
    public void Raiserror_WithArgs()
    {
        var o = Conv(@"DECLARE @id INT = 5;
RAISERROR('Kunde %d fehlt', 16, 1, @id);");
        Has(o, "RAISE_APPLICATION_ERROR(-20000, 'Kunde ' || TO_CHAR(v_id) || ' fehlt');");
    }

    [Fact]
    public void ResultSet_InProcedure_UsesReturnResult()
    {
        var o = Conv("CREATE PROCEDURE p AS SELECT * FROM t");
        Has(o, "OPEN c_result1 FOR SELECT * FROM t;");
        Has(o, "DBMS_SQL.RETURN_RESULT(c_result1);");
    }

    [Fact]
    public void ScopeIdentity_BecomesReturningInto()
    {
        var o = Conv(@"CREATE TABLE t (Id INT IDENTITY(1,1), Name VARCHAR(10))
GO
CREATE PROCEDURE p @Name VARCHAR(10), @Id INT OUTPUT AS
BEGIN
    INSERT INTO t (Name) VALUES (@Name);
    SET @Id = SCOPE_IDENTITY();
END");
        Has(o, "INSERT INTO t (Name) VALUES (p_Name) RETURNING Id INTO p_Id;");
    }

    [Fact]
    public void UpdateFromJoin_BecomesMerge()
    {
        var o = Conv("UPDATE r SET r.Status = s.Status FROM dbo.Rechnung r INNER JOIN dbo.Import s ON s.Id = r.Id WHERE s.Ok = 1");
        Has(o, "MERGE INTO Rechnung r USING Import s ON (s.Id = r.Id) WHEN MATCHED THEN UPDATE SET r.Status = s.Status WHERE s.Ok = 1;");
    }

    [Fact]
    public void TempTable_InBlock_BecomesGttPrereq()
    {
        var o = Conv(@"DECLARE @x INT = 1;
CREATE TABLE #tmp (Id INT);
INSERT INTO #tmp VALUES (@x);");
        Has(o, "CREATE GLOBAL TEMPORARY TABLE tmp_tmp ( Id NUMBER(10) ) ON COMMIT PRESERVE ROWS;");
        Has(o, "INSERT INTO tmp_tmp VALUES (v_x);");
    }

    [Fact]
    public void ScalarFunction()
    {
        var o = Conv(@"CREATE FUNCTION dbo.fnDoppelt (@x INT) RETURNS INT AS
BEGIN
    RETURN @x * 2;
END");
        Has(o, "CREATE OR REPLACE FUNCTION fnDoppelt ( p_x IN NUMBER ) RETURN NUMBER AS BEGIN RETURN p_x * 2; END fnDoppelt;");
    }

    [Fact]
    public void DateLiteral_AssignedToDateVariable()
    {
        Has(Conv("DECLARE @d DATE = '2024-12-31'; PRINT @d;"), "v_d DATE := TO_DATE('2024-12-31', 'YYYY-MM-DD');");
    }

    [Fact]
    public void TableNamedLikeFunction_IsNotMapped()
    {
        var o = Conv("INSERT INTO log (msg) SELECT ISNULL(a.x, '') FROM a JOIN b ON ISNULL(a.k, 0) = b.k");
        Has(o, "INSERT INTO log (msg)");
        Has(o, "ON NVL(a.k, 0) = b.k");
    }

    [Fact]
    public void EmptyString_ProducesWarning()
    {
        var r = new TSqlToPlSqlConverter().Convert("SELECT * FROM t WHERE x <> ''");
        Assert.Contains(r.Warnings, w => w.Contains("Leerstring"));
    }
}
